<?php

namespace App\Controllers\admins;

use App\Controllers\BaseController;

class Report extends BaseController
{
    public function suppliers_xls()
    {
        $filename = 'SUPPLIER USERS ACCOUNT REPORT' . date('YmdHis');
        header("Cache-Control: public");
        header("Content-Type: application/octet-stream");
        header("Content-Type: application/vnd.ms-excel; charset=utf-8");
        header("Content-disposition: attachment; filename=" . $filename . ".xls");
        echo '<i>Date Generated : ' . date('F d, Y') . '</i><br>';
        echo '<i>Generated Thru : altsportal.com</i><br>';
        echo '<i>Generated by : ' . session('admin_username') . '</i><br>';
        echo '<i>Report Title : Supplier Users Account Report</i><br>';
        echo '<style type="text/css">
            th,
            td {
                border: 1px dotted black;
                font-size: 12px;
                font-family: Calibri, sans-serif; /* Set font style to Calibri */
            }
            i, b {
                font-family: Calibri, sans-serif; /* Optional: For italic and bold texts */
            }
         </style>';
        echo '<center>';
        echo '<h3>Users Account Report as of ' . date("F d, Y") . '</h3>';
        echo '</center>';
        echo '<table>
                <tr>
                    <th>No</th>
                    <th>Agency/Company</th>
                    <th>Username</th>
                    <th>Password</th>
                    <th>Status</th>
                    <th>Date Created</th>
                    <th>Login</th>
                    <th>Last Login</th>
                </tr>';
        $num = 1;
        $query = $this->setup_model->users_account();
        foreach ($query as $row) {

            $last_login = "";
            if ($row['last_login'] != "") {

                $last_login = date('m/d/Y', strtotime($row['last_login']));
            }

            $first_login = "";
            if ($row['first_login'] != "") {

                $first_login = date('m/d/Y', strtotime($row['first_login']));
            }

            if ($row['status'] == 1) {
                $status = 'Active';
            } else {
                $status = 'Inactive';
            }

            echo "<tr>
					<td>" . $num . "</td>
					<td>" . $row['supplier'] . "</td>
					<td>" . $row['username'] . "</td>
					<td>Altsportal2019</td>
					<td>" . $status . "</td>
					<td>" . date('m/d/Y', strtotime($row['created_at'])) . "</td>
					<td>" . $first_login . "</td>
					<td>" . $last_login . "</td>";
            echo "</tr>";
            $num++;
        }
    }
}
